import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
const target = new URL('supabase/functions/seller-os-media/', root);
const codecs = [
  ['jpeg', '1.6.0', 'codec/dec/mozjpeg_dec.wasm', 166470],
  ['png', '3.1.1', 'codec/pkg/squoosh_png_bg.wasm', 181088],
  ['webp', '1.5.0', 'codec/dec/webp_dec.wasm', 137960],
];
let source = '// Generated by scripts/prepare-media-codecs.mjs; server-only decode WASM.\nexport const wasmBytes = {\n';
let notice = 'Server-only jSquash decode WASM provenance (not user photos).\nhttps://github.com/jamsinclair/jSquash\n\n';
for (const [name, version, path, size] of codecs) {
  const base = new URL(`node_modules/@jsquash/${name}/`, root);
  const pkg = JSON.parse(await readFile(new URL('package.json', base), 'utf8'));
  if (pkg.version !== version || pkg.license !== 'Apache-2.0') throw new Error(`Unexpected codec provenance ${name}`);
  const bytes = await readFile(new URL(path, base));
  if (bytes.length !== size) throw new Error(`Unexpected WASM size ${name}`);
  source += `  ${name}: Uint8Array.from(atob('${bytes.toString('base64')}'), c => c.charCodeAt(0)),\n`;
  notice += `@jsquash/${name}@${version} ${path}\nbytes=${size} sha256=${createHash('sha256').update(bytes).digest('hex')}\nlicense=${pkg.license}\n`;
  notice += await readFile(new URL('LICENSE', base), 'utf8') + '\n\n';
}
source += '};\n'; await mkdir(target, { recursive: true });
await writeFile(new URL('codecBytes.js', target), source);
await writeFile(new URL('CODECS_NOTICE.txt', target), notice);
console.log(`Generated 3 decoder assets, 485518 WASM bytes, ${Buffer.byteLength(source)} JS bytes.`);
